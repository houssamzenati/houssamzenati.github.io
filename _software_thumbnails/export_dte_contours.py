#!/usr/bin/env python3
"""Export the saved DTE experiment surfaces as editable TikZ paths.

Only needed when changing the contour representation. Normal thumbnail builds
use the checked-in TeX and require no NumPy or Matplotlib installation.
"""

from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.path import Path as PlotPath
import numpy as np


HERE = Path(__file__).resolve().parent
DATA = HERE / "sources/interpretable-dte-locations.npz"
OUTPUT = HERE / "miniatures/interpretable-dte-contours.tex"
PANEL_WIDTH = 3.0


def tikz_path(path, xmin, xmax, ymin, ymax):
    commands = []
    for vertices, code in path.iter_segments(curves=False, simplify=False):
        if code == PlotPath.CLOSEPOLY:
            commands.append("-- cycle")
            continue
        x, y = vertices
        scale = PANEL_WIDTH / (xmax - xmin)
        point = f"({scale * (x - xmin):.4f},{scale * (y - ymin):.4f})"
        commands.append(point if code == PlotPath.MOVETO else f"-- {point}")
    return " ".join(commands)


def main():
    data = np.load(DATA)
    xs = np.unique(data["grid"][:, 0])
    ys = np.unique(data["grid"][:, 1])
    bounds = xs.min(), xs.max(), ys.min(), ys.max()
    # Both experiments retain the same absolute scale and exact grid maximizers.
    levels = np.linspace(data["scores"].min(), data["scores"].max(), 9)
    output = [
        "% Generated by export_dte_contours.py from saved experimental results.",
        "% Green shading = joint DR training criterion, not a density or p-value.",
        "% Common colour scale and equal x/y spatial scale; no per-panel normalization.",
    ]
    for index, name in enumerate(("central", "left")):
        figure, axis = plt.subplots()
        score = data["scores"][index].reshape(len(ys), len(xs))
        surface = axis.contourf(xs, ys, score, levels=levels)
        lines = axis.contour(xs, ys, score, levels=levels[1:-1:2])
        output.append("\\newcommand{\\" + name + "field}{%")
        for band, path in enumerate(surface.get_paths()):
            shade = 5 + band * 7
            output.append(r"\path[fill=softgreen!" + str(shade) + ",draw=none,even odd rule] " + tikz_path(path, *bounds) + ";")
        for path in lines.get_paths():
            output.append(r"\path[draw=softgreen!70,line width=.35pt,fill=none] " + tikz_path(path, *bounds) + ";")
        for key, label in (("fixed", "one"), ("selected", "two")):
            x, y = data[key][index]
            scale = PANEL_WIDTH / (bounds[1] - bounds[0])
            x = scale * (x - bounds[0])
            y = scale * (y - bounds[2])
            output.append(f"\\coordinate (v{label}) at ({x:.6f},{y:.6f});")
        output.append("}")
        plt.close(figure)
    OUTPUT.write_text("\n".join(output) + "\n")
    print(f"Exported {OUTPUT}")


if __name__ == "__main__":
    main()
